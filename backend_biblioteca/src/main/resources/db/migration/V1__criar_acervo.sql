-- Acervo: gêneros e livros (RF01, RF02).
-- Migrations precisam rodar no H2 (dev/test) e no PostgreSQL (prod):
-- use apenas SQL padrão (sem jsonb, serial, arrays etc.).

CREATE TABLE genero (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_genero_nome UNIQUE (nome)
);

CREATE TABLE livro (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn             VARCHAR(20),
    titulo           VARCHAR(255) NOT NULL,
    autor            VARCHAR(255) NOT NULL,
    editora          VARCHAR(255),
    ano_publicacao   INTEGER,
    status           VARCHAR(20)  NOT NULL,
    data_cadastro    TIMESTAMP WITH TIME ZONE NOT NULL,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_livro_isbn UNIQUE (isbn)
);

CREATE TABLE livro_genero (
    livro_id  BIGINT NOT NULL,
    genero_id BIGINT NOT NULL,
    PRIMARY KEY (livro_id, genero_id),
    CONSTRAINT fk_livro_genero_livro  FOREIGN KEY (livro_id)  REFERENCES livro (id),
    CONSTRAINT fk_livro_genero_genero FOREIGN KEY (genero_id) REFERENCES genero (id)
);

CREATE INDEX idx_livro_titulo ON livro (titulo);
CREATE INDEX idx_livro_autor  ON livro (autor);
