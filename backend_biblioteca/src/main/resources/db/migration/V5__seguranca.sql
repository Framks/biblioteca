-- Segurança (seção 6): bloqueio de login, sessões, refresh tokens, blocklist de JWT e auditoria (RF15, RF16, RF20, RF21).

-- 6.1: bloqueio após tentativas erradas
ALTER TABLE usuario ADD COLUMN tentativas_login_falhas INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE usuario ADD COLUMN bloqueado_ate TIMESTAMP WITH TIME ZONE;

-- 6.5: cada login abre uma sessão vinculada ao dispositivo (device_id) e ao navegador (User-Agent)
CREATE TABLE sessao (
    id               UUID PRIMARY KEY,               -- claim "sid" do JWT
    usuario_id       BIGINT       NOT NULL,
    device_id_hash   VARCHAR(64)  NOT NULL,          -- SHA-256 do cookie device_id (o valor em si nunca é gravado)
    ip               VARCHAR(64)  NOT NULL,
    user_agent       VARCHAR(500) NOT NULL,
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_acesso    TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    revogada_em      TIMESTAMP WITH TIME ZONE,
    motivo_revogacao VARCHAR(50),
    CONSTRAINT fk_sessao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
CREATE INDEX idx_sessao_usuario ON sessao (usuario_id);

-- 6.3: refresh tokens rotativos. usado_em preenchido = já trocado; reapresentá-lo revoga a sessão.
CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id   UUID        NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,                -- SHA-256; o token em si só existe no cookie do cliente
    emitido_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    usado_em    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_sessao FOREIGN KEY (sessao_id) REFERENCES sessao (id)
);

-- 6.4: access tokens revogados antes de expirar (logout). Registros vencidos são limpos periodicamente.
CREATE TABLE token_blocklist (
    jti       VARCHAR(64) PRIMARY KEY,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo    VARCHAR(50) NOT NULL
);

-- RF21: trilha de auditoria
CREATE TABLE auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT,                              -- nulo em ações anônimas (ex.: login com e-mail inexistente)
    acao        VARCHAR(50)   NOT NULL,
    entidade    VARCHAR(50),
    entidade_id BIGINT,
    detalhes    VARCHAR(1000),
    ip          VARCHAR(64),
    data_hora   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
CREATE INDEX idx_auditoria_data ON auditoria (data_hora);
CREATE INDEX idx_auditoria_usuario ON auditoria (usuario_id);
