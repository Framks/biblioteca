-- Exemplares físicos de cada livro (RF03).

CREATE TABLE exemplar (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(30) NOT NULL,
    livro_id         BIGINT      NOT NULL,
    condicao         VARCHAR(20) NOT NULL,
    status           VARCHAR(20) NOT NULL,
    data_cadastro    TIMESTAMP WITH TIME ZONE NOT NULL,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_exemplar_codigo UNIQUE (codigo),
    CONSTRAINT fk_exemplar_livro FOREIGN KEY (livro_id) REFERENCES livro (id)
);

CREATE INDEX idx_exemplar_livro_status ON exemplar (livro_id, status);
