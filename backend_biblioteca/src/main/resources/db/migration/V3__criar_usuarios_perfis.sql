-- Usuários (leitores, funcionários, administradores), perfis e permissões (RF06, RF17, RF18, seção 7).

CREATE TABLE permissao (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(50)  NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    CONSTRAINT uk_permissao_codigo UNIQUE (codigo)
);

CREATE TABLE perfil (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(50)  NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT uk_perfil_nome UNIQUE (nome)
);

CREATE TABLE perfil_permissao (
    perfil_id    BIGINT NOT NULL,
    permissao_id BIGINT NOT NULL,
    PRIMARY KEY (perfil_id, permissao_id),
    CONSTRAINT fk_perfil_permissao_perfil    FOREIGN KEY (perfil_id)    REFERENCES perfil (id),
    CONSTRAINT fk_perfil_permissao_permissao FOREIGN KEY (permissao_id) REFERENCES permissao (id)
);

CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(255) NOT NULL,
    email            VARCHAR(255),
    senha_hash       VARCHAR(100),             -- nulo = sem acesso ao sistema (leitor comum)
    tipo_documento   VARCHAR(10),
    documento        VARCHAR(20),              -- só dígitos (CPF) ou letras e dígitos (RG)
    telefone         VARCHAR(20),
    endereco         VARCHAR(500),
    perfil_id        BIGINT       NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    suspenso_ate     DATE,                     -- RN07
    data_cadastro    TIMESTAMP WITH TIME ZONE NOT NULL,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_usuario_email     UNIQUE (email),
    CONSTRAINT uk_usuario_documento UNIQUE (tipo_documento, documento),
    CONSTRAINT fk_usuario_perfil    FOREIGN KEY (perfil_id) REFERENCES perfil (id)
);

CREATE INDEX idx_usuario_nome ON usuario (nome);

