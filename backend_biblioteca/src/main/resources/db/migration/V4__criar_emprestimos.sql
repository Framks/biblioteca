-- Controle de concorrência otimista: impede dois empréstimos simultâneos do mesmo exemplar.
ALTER TABLE exemplar ADD COLUMN versao BIGINT DEFAULT 0 NOT NULL;

CREATE TABLE emprestimo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leitor_id       BIGINT       NOT NULL,
    operador_id     BIGINT       NOT NULL,
    data_emprestimo TIMESTAMP WITH TIME ZONE NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    observacao      VARCHAR(500),
    CONSTRAINT fk_emprestimo_leitor   FOREIGN KEY (leitor_id)   REFERENCES usuario (id),
    CONSTRAINT fk_emprestimo_operador FOREIGN KEY (operador_id) REFERENCES usuario (id)
);

CREATE TABLE emprestimo_item (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id           BIGINT      NOT NULL,
    exemplar_id             BIGINT      NOT NULL,
    data_devolucao_prevista DATE        NOT NULL,
    data_devolucao_real     TIMESTAMP WITH TIME ZONE,   -- nulo = ainda não devolvido
    renovacoes              INTEGER     NOT NULL,
    condicao_retirada       VARCHAR(20) NOT NULL,
    condicao_devolucao      VARCHAR(20),
    recebido_por            BIGINT,
    CONSTRAINT fk_item_emprestimo   FOREIGN KEY (emprestimo_id) REFERENCES emprestimo (id),
    CONSTRAINT fk_item_exemplar     FOREIGN KEY (exemplar_id)   REFERENCES exemplar (id),
    CONSTRAINT fk_item_recebido_por FOREIGN KEY (recebido_por)  REFERENCES usuario (id)
);

CREATE INDEX idx_emprestimo_leitor        ON emprestimo (leitor_id);
CREATE INDEX idx_emprestimo_data          ON emprestimo (data_emprestimo);
CREATE INDEX idx_item_emprestimo          ON emprestimo_item (emprestimo_id);
CREATE INDEX idx_item_exemplar            ON emprestimo_item (exemplar_id);
CREATE INDEX idx_item_pendente            ON emprestimo_item (data_devolucao_real, data_devolucao_prevista);
